-- CDD APP SUITE: Supabase schema
-- Run this whole script once in Supabase Dashboard > SQL Editor.
-- Security model: public users can read the launcher catalogue; only signed-in users can modify it.

create table if not exists public.apps (
  id bigint primary key,
  title text not null,
  path text not null,
  category text not null default 'ทั่วไป',
  badge_color text not null default 'blue',
  description text not null default '',
  version text not null default '',
  icon text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.app_settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  action text not null,
  details jsonb not null default '{}'::jsonb,
  actor uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.apps enable row level security;
alter table public.app_settings enable row level security;
alter table public.audit_logs enable row level security;

drop policy if exists "Public can read apps" on public.apps;
create policy "Public can read apps" on public.apps for select using (true);
drop policy if exists "Signed-in users manage apps" on public.apps;
create policy "Signed-in users manage apps" on public.apps for all to authenticated using (true) with check (true);

drop policy if exists "Public can read settings" on public.app_settings;
create policy "Public can read settings" on public.app_settings for select using (true);
drop policy if exists "Signed-in users manage settings" on public.app_settings;
create policy "Signed-in users manage settings" on public.app_settings for all to authenticated using (true) with check (true);

drop policy if exists "Signed-in users read audit logs" on public.audit_logs;
create policy "Signed-in users read audit logs" on public.audit_logs for select to authenticated using (true);
drop policy if exists "Signed-in users write audit logs" on public.audit_logs;
create policy "Signed-in users write audit logs" on public.audit_logs for insert to authenticated with check (actor = auth.uid());

-- Atomic replacement used by the Import/Save workflow.
create or replace function public.replace_apps(payload jsonb)
returns void
language plpgsql
security invoker
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'ต้องเข้าสู่ระบบผู้ดูแลก่อนบันทึกข้อมูล';
  end if;
  if jsonb_typeof(payload) <> 'array' then
    raise exception 'ข้อมูลนำเข้าต้องเป็นรายการแบบ array';
  end if;
  delete from public.apps;
  insert into public.apps (id, title, path, category, badge_color, description, version, icon)
  select x.id, x.title, x.path, coalesce(x.category, 'ทั่วไป'), coalesce(x.badge_color, 'blue'),
         coalesce(x.description, ''), coalesce(x.version, ''), coalesce(x.icon, '')
  from jsonb_to_recordset(payload) as x(
    id bigint, title text, path text, category text, badge_color text, description text, version text, icon text
  );
end;
$$;

grant execute on function public.replace_apps(jsonb) to authenticated;

